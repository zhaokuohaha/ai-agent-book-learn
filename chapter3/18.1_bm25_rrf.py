"""chapter3/18.1_bm25_rrf.py — RAG 基础（下）· 一：BM25 稀疏检索与 RRF 混合

本实验新增的主概念：BM25 稀疏检索（伴生：RRF 融合）。Cross-Encoder 重排与
闭环在 18.2，检索质量三指标在 18.3。

BM25：关键词精确匹配的回归（承接 D17 的"书后术语索引页"比喻）
    稠密检索是语义地图（意思近就算近），稀疏检索是倒排索引（字面命中才算数）。
    TF-IDF 直觉：词在本文档出现越多、全语料越稀有，越重要；它有两个坑——
    词频线性涨（出现 10 次得 10 倍分）、长文档占便宜。BM25 两参数修正：
    k1 词频饱和（10 次不比 5 次强一倍，边际递减）、b 长度归一化（字多不加分）。
    细节：BM25 的 IDF 是变体公式——分子为"不含该词的文档数"（+0.5 平滑），
    词出现在过半文档时会变负，实现必须设下限（见 common/retriever.py 的 _idf）。

RRF：序数可比，基数不可比
    两路得分分布迥异（余弦 0~1 vs BM25 可到几十），直接加权 = 拿人民币和
    美元直接相加。RRF 完全抛弃原始得分，只用排名倒数求和 Σ 1/(k+rank)。

问题先行（为什么需要第二路引擎）：昨天 D17 实测稠密检索的平局——"退货要
    多久到账"下退货块与配送块同为 0.50（"要多久"撞上配送的时长讨论），
    语义地图分不出字面；镜像案例"包邮有什么条件"——BM25 空手（"包邮"不在
    语料，得分全 0 只能瞎排），稠密靠语义命中"满 99 元免运费"。两路各有
    盲区 → 混合检索（作业 ① 的双路检索）。

运行：uv run python -X utf8 chapter3/18.1_bm25_rrf.py（零 LLM 调用，本地嵌入）
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.retriever import BM25Index, DenseIndex, load_faq, rrf_fuse

if __name__ == "__main__":
    chunks, topics = load_faq()
    print(f"语料：{len(chunks)} 块 = {len(topics)} 个主题（doc_id 0-{len(topics) - 1}）")
    bm25 = BM25Index(chunks)
    dense = DenseIndex(chunks)

    print("\n=== Part 0：问题先行——稠密路的平局（D17 实测遗留） ===")
    q = "退货要多久到账"
    for s, i in dense.search(q, 5):
        print(f"  {s:+.2f}  [{topics[i]}]")
    print("  → 配送/开票/退货三块挤在 0.01 分差内：'要多久'撞上一切带时限的块（48/72 小时、")
    print("    30 天）——语义地图对字面无感，平局只能靠小数点后两位裁决")

    print("\n=== Part 1：BM25 手感——稀有词更值钱，词频会饱和 ===")
    for w in ("退货", "政策"):
        print(f"  IDF('{w}')：{bm25.df[w]}/{bm25.N} 篇文档含它 → {bm25._idf(w):.2f}")
    idf = bm25._idf("退款")
    sat = [idf * tf * (bm25.k1 + 1) / (tf + bm25.k1) for tf in (1, 5, 10)]
    print(f"  词频饱和（'退款'，k1={bm25.k1}）：tf=1→{sat[0]:.2f}，tf=5→{sat[1]:.2f}，tf=10→{sat[2]:.2f}")
    print("  → 词频涨 10 倍，得分只涨约 57%（边际递减）；'退货'比'政策'稀有，单次贡献更大")

    print("\n=== Part 2：双引擎各有盲区——两次翻车，两次互补 ===")
    for q, story in [("退货要多久到账", "稠密平局 → BM25 字面破局"),
                     ("包邮有什么条件", "BM25 空手瞎排 → 稠密语义兜底")]:
        print(f"\n查询「{q}」（{story}）")
        print("  稠密 top-2：", [(topics[i], round(s, 2)) for s, i in dense.search(q, 2)])
        print("  BM25  top-2：", [(topics[i], round(s, 2)) for s, i in bm25.search(q, 2)])
    print("  → 题一：BM25 把退货（1.69）与配送（0）一刀切开，平局破了；题二：'包邮'不在")
    print("    语料，BM25 全 0 只能瞎排，稠密靠'包邮≈免运费'把配送拉到第二（0.38）——")
    print("    两路各自的盲区，恰是对方的强区：这就是双路混合的理由")

    print("\n=== Part 3：RRF 融合——两路投票，共识才算数 ===")
    print("  停一停：为什么融合用排名、不用两路的原始得分？（先想 3 秒再看下一行）")
    print("  答：余弦 0~1、BM25 可到几十，量纲与分布都不可比（人民币加美元）；排名是")
    print("      两路共同的语言——序数可比、基数不可比，RRF 只用排名就天然免疫量纲问题")
    q = "退货要多久到账"
    d_rank = [i for _, i in dense.search(q, 5)]
    b_rank = [i for _, i in bm25.search(q, 5)]
    fused = rrf_fuse([d_rank, b_rank])
    print(f"\n查询「{q}」的融合明细（融合后顺序）：")
    for i in fused:
        print(f"  [{topics[i]}]  稠密第 {d_rank.index(i) + 1} 名 + BM25 第 {b_rank.index(i) + 1} 名")
    print("  → 退款双路第一，铁票居首。但第二三名有盖子：配送（稠密2+BM25四）与")
    print("    退货（稠密4+BM25二）的 RRF 得分数学上完全相等（1/62+1/64 对称），并列")
    print("    只靠插入顺序裁决；开票（双第三，2/63）也只差百万分之八——RRF 是粗粒度")
    print("    投票：名次之和对'哪路更可信'无感，近并列分不开")
    print("    → 排名缝合到此为止。谁来逐对细看'这段话能不能回答这个问题'？——18.2 的重排")

