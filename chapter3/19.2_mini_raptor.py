"""chapter3/19.2_mini_raptor.py — 结构化索引 · 二：两层迷你 RAPTOR 摘要树

本实验新增的主概念：RAPTOR 树（作业②）——把知识组织成"摘要树"。

三层讲解
    直觉：OLAP 的 rollup——日/周/月多粒度聚合，报表既能看大盘又能钻明细。
    机制：chunk 做叶子 → 语义相近的聚一组 → 每组生成父节点摘要 → 递归向上
          （生产：聚类算法 + LLM 生成摘要；本实验手动分组、手写摘要——
          作业②的要求，聚焦"树上检索怎么路由"这一步）
        [父·售后摘要]      [父·权益摘要]      [父·物流票据摘要]
         ├─退款政策(叶)      ├─会员制度(叶)      ├─配送说明(叶)
         └─退货换货(叶)                         └─开票政策(叶)
    代码落点：父摘要与叶子一起进 DenseIndex；宏观问题期望命中父（一次拿到
          全貌），细节问题期望命中叶（答案要素齐全）——检索在粒度间穿梭。

承接 19.1：统计摘要/规则卡是"整库一张卡"，RAPTOR 是"每层一组卡"——
    都是把离线提炼的产物入库，粒度从粗到细。

运行：uv run python -X utf8 chapter3/19.2_mini_raptor.py（零 LLM 调用，本地嵌入）
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.retriever import DenseIndex, load_faq

# 两层迷你 RAPTOR：D17 的 5 块 FAQ 按主题聚 3 组（关键词分组的手段，作业②），
# 父摘要手写（生产用 LLM 逐组生成——本质是"局部统计摘要"，同 19.1 的离线提炼）
GROUPS = [
    ("售后政策总览：签收后 7 天内可全额退款、原路退回 3-5 个工作日到账；"
     "退货需吊牌完整，换货仅限同款不同尺码，不支持跨款换货。",
     {"退款政策", "退货与换货"}),
    ("购物权益总览：黄金会员享 95 折优惠与专属客服通道，年消费满 5000 元自动升级。",
     {"会员制度"}),
    ("物流与票据总览：默认顺丰，下单后 48 小时内发货、偏远地区延长至 72 小时，"
     "满 99 元免运费；支持电子普通发票，需下单后 30 天内提交抬头。",
     {"配送说明", "开票政策"}),
]

# 宏观问题答"大盘"（单个叶子答不了），细节问题答"某一条"
QUESTIONS = [
    ("这家店售后方面整体有什么政策？", "父·摘要（一次拿到售后全貌）"),
    ("黄金会员有什么权益？", "叶（单主题细节）"),
]


if __name__ == "__main__":
    chunks, topics = load_faq()

    # 搭树：父节点 + 叶子一起入索引（doc_id 带类型标记）
    nodes = []
    for parent_text, topic_names in GROUPS:
        nodes.append((f"[父] {parent_text}", "父·摘要"))
        nodes += [(c, f"叶·{t}") for c, t in zip(chunks, topics) if t in topic_names]
    texts = [t for t, _ in nodes]
    index = DenseIndex(texts)
    print(f"迷你 RAPTOR：{len(GROUPS)} 个父摘要 + {len(texts) - len(GROUPS)} 个叶子，共 {len(texts)} 节点")

    print("\n=== 检索路由：宏观问题走摘要，细节问题走叶子 ===")
    for q, expect in QUESTIONS:
        print(f"\n「{q}」（期望 top-1：{expect}）")
        for score, i in index.search(q, 3):
            print(f"  {score:+.2f}  [{nodes[i][1]}] {texts[i][:26]}…")

    print("\n  → 真实观察：宏观题父摘要明显胜出（0.51 vs 0.41，两叶综合才答得了大盘）；")
    print("    细节题父子几乎平手（0.64 vs 0.64）——会员组只有 1 个叶子，父摘要≈叶子")
    print("    复述，粒度收益自然为零；组越大、父子差异越大，路由才越有价值")

    print("\n=== 代价对照：树不是白搭的 ===")
    print("  父摘要覆盖面广但丢细节（'3-5 个工作日'不会出现在总览里）——宏观/细节")
    print("  各取所需；生产代价：聚类 + 逐组 LLM 摘要的构建成本，且摘要失真会")
    print("  在高层节点放大。值不值得，回到决策标准：查询要不要多层次导航")

