"""chapter6/38.1_cascade_latency.py — 级联流水线的延迟瀑布与流式压缩

本实验新增的主概念是「流式感知四手段」——级联流水线（VAD→ASR→LLM→
TTS 四级串联，微服务串行调用链的同构）的每级延迟串行累积：静音阈值
等说完、转写要时间、首 token 要时间、首包合成要时间——用户听到第一
个字时，瀑布已经流完四级。四个手段把「完全串行」改成「边到边处理」：

    ASR 边听边转    说话过程中流式产出临时转录（转写与说话重叠）
    LLM 推测执行    临时转录先送思考，最终一致不重调、不一致取消重算
                   ——CPU 分支预测 + 推测执行的思想
    LLM 分段输出    第一段可播报文本立即交 TTS，不等完整回复
    TTS 增量合成    持续返回音频块，生成/合成/播放重叠

本实验用时间轴推演两级管线（延迟结构是数字概念——时间轴即本体，不
真 sleep；36.1 真跑是因为抢占是行为概念需要真实发生）。延迟量级取
现实典型值（毫秒），场景固定为一句 3 秒的用户语音。

运行：uv run python -X utf8 chapter6/38.1_cascade_latency.py（零 API，瞬时）
"""

SPEECH_MS = 3000  # 用户这句语音的时长

# 各级延迟模型（毫秒，现实典型量级；来源即「延迟瀑布」的每一级）
SERIAL = [
    ("VAD", 600, "静音阈值：等 ~600ms 无声才确认说完"),
    ("ASR", 800, "转写 3s 音频（串行版：说完才开始转）"),
    ("LLM", 2000, "首 token 500 + 完整生成 1500（串行版：等最终文本）"),
    ("TTS", 1500, "首包合成 300 + 播放 1200（串行版：等完整回复）"),
]


def bar(start: int, end: int, label: str, width: int = 40) -> str:
    total = SPEECH_MS + 4900
    l, r = round(start / total * width), round(end / total * width)
    return " " * l + "#" * max(1, r - l) + f"  {start}→{end}ms  {label}"


if __name__ == "__main__":
    print("=== A 串行（听完 → 转完 → 想完 → 说完）：延迟瀑布逐级累积 ===")
    t, first_serial = 0, 0
    for name, ms, why in SERIAL:
        if name == "TTS":
            first_serial = t + 300  # 听到第一个字 = TTS 首包（前面已等完整 LLM 生成）
        print(f"  [{name}] {bar(t, t + ms, why)}")
        t += ms
    print(f"  → 听到第一个字：{first_serial}ms｜说完→首响的响应间隔 {first_serial - SPEECH_MS}ms\n")

    print("=== B 流式（边听边转 → 先想后确认 → 出一段念一段 → 边合成边播） ===")
    print(f"  [说话] {bar(0, SPEECH_MS, '用户语音流（3s）')}")
    print(f"  [ASR ] {bar(500, SPEECH_MS, '边听边转：转写与说话重叠，0 额外延迟')}")
    print(f"  [LLM ] {bar(2400, 2900, '推测执行：临时转录先行思考（分支预测思想）')}")
    print(f"  [VAD ] {bar(SPEECH_MS, SPEECH_MS + 600, '静音确认（与生成重叠，退出关键路径）')}")
    print(f"  [LLM ] {bar(2900, 3200, '推测路径继续生成，首段 200ms 出片（赌确认一致）')}")
    print(f"  [TTS ] {bar(3200, 3500, '增量合成：首包 300ms 即出声（在确认前——激进）')}")
    print(f"  [TTS ] {bar(3500, 4900, '后续段与生成重叠，边合成边播；确认@3600 一致不重算')}")
    first_stream = 3500
    print(f"  → 听到第一个字：{first_stream}ms｜说完→首响的响应间隔 {first_stream - SPEECH_MS}ms\n")

    print(f"=== 压缩结论：首响 {first_serial}→{first_stream}ms、响应间隔 "
          f"{first_serial - SPEECH_MS}→{first_stream - SPEECH_MS}ms（总完成都是 ~4900ms） ===")
    print("  四手段没消灭任何一级耗时——只是让它们不在同一条直线上排队：")
    print("  转写藏进说话、思考抢在确认前、出片不等全文、合成跟着播放走；")
    print("  VAD/ASR/大半 LLM 延迟退出关键路径（语音越长重叠收益越大——")
    print("  ASR/VAD 占比下降、分段输出占比上升）。代价：推测执行的赌注——")
    print("  确认不一致就要取消已播内容（本实验只推演一致路径）。再往下两级：")
    print("  流式听觉（识别+理解同模型，声学事件标记 speak_start/emotion/laugh")
    print("  ——Agent 能感知犹豫与打断）；全双工把「该谁说话」变成模型的持续决策。")

