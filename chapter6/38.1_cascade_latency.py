# 执行逻辑（零 API 瞬时完成，纯时间轴推演）：
#   1. A 串行：四级延迟顺序累加（600+800+2000+1500）；串行版 LLM 等
#      完整生成才交 TTS → 首响 = 600+800+2000+300 = 3700ms
#   2. B 流式：四手段重叠规则标注各级起止——转写藏进说话（500~3000）、
#      思考 2400 抢跑、VAD 与生成重叠退出关键路径、首段 3200 出片、
#      首包 3500 出声（在确认 3600 之前——推测执行的赌注）
# 验证内容（数字确定性，可手算复核）：
